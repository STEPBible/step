/* Extends HTML with the standard 4-panel layout, so that your page needs only

     <j-4panel-layout></j-4panel-layout>

   in place of the full set of divs.

   This sets up something which looks like this:

     +------------------------------+------------------------------+
     |                              |                              |
     |          Search box          |           Info box           |
     |                              |                              |
     +------------------------------+------------------------------+
     |                              |                              |
     |       Scripture window       |     Application-specific     |
     |                              |                              |
     +------------------------------+------------------------------+


   The search box, scripture window and info box are basically standard
   elements: you merely need to arrange to populate them as necessary.
   (The search box raises events when user input events occur, and you
   can hook on to them.  See j_inputBoxWithOptionsTable.js for details.)

   The application-specific area is one into which you add the stuff
   which is genuinely specific to your application -- maps, family trees,
   etc.

   You need to include this in order to have <j-4panel-layout> available.
   You also need to create and call 'initialise' on an instance in order
   to initialise the various elements which make up the 4-panel display.

   A Jamieson   STEPBible   Oct 2026 (My code, but with a lot of Claude ...)
*/

