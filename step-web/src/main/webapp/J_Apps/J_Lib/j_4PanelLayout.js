/* Generated by Claude.  I haven't tried to understand either the comments here
   or the code.

   The layout brings its own stylesheet, so the page doesn't have to link to it.
   j_multiPanelLayout.css itself @imports j_common.css (the colour variables
   which the components rely on, and the base styles), so that comes with it.

   The link is added once, whatever the number of layouts on the page; and if
   the page also has a <link> to the same file, that one is used instead.

   Returns a promise which resolves when the stylesheet (and anything it
   imports) has loaded. */

function loadStylesheet (url)
{
    const alreadyThere = [...document.querySelectorAll('link[rel="stylesheet"]')].find(link => link.href === url.href);
    if (alreadyThere) return alreadyThere.sheet ? Promise.resolve() : new Promise(resolve => {
	alreadyThere.addEventListener("load", resolve, { once: true });
	alreadyThere.addEventListener("error", resolve, { once: true });
    });

    return new Promise(resolve => {
	const link = document.createElement("link");
	link.rel = "stylesheet";
	link.href = url.href;
	link.addEventListener("load", resolve, { once: true });
	link.addEventListener("error", resolve, { once: true });   // Carry on regardless: better unstyled than invisible forever.
	document.head.prepend(link);   // First, not last: the page's own <style> overrides (column widths etc.) must come later in the document so that they win.
    });
}

const stylesheetLoaded = loadStylesheet(new URL("./j_multiPanelLayout.css", import.meta.url));


/******************************************************************************/
export class J_4PanelLayout extends HTMLElement
{
    /**************************************************************************/
    /* You need to call this to initialise everything.
 
       - nameForApplicationSpecificTab is the name which appears on the
         application-specific tab on small screens.  (On small screens,
	 three of the four tabs have standard names reflecting the fact that
	 they always contain the search box, the scripture window, and the
         info-box.  But the fourth will vary by application, so we need to
	 know what to call it.)

       - options is optional (!), and may contain:

           resizablePanels  Default [].  Names the panels you want the user to be
                            able to resize: any of "search", "scripture",
                            "infoBox" and "app".  No panel is resizable
                            unless you list it.  Each one listed gets a
                            handle at the corner facing into the page (so the
                            search box, at top left, gets one at its bottom right,
                            and the application-specific panel, at bottom right,
                            gets one at its top left), and draggable edges.  A
                            panel can be enlarged (over the top of its neighbours)
                            but not made smaller than its original size.

           edgeDragging     Default true.  Lets the user drag the edges of a
                            resizable panel as well as its corner handle.  Set
                            it to false if you want the handles only.

       - shareableLinkGenerator: Code used to generate a shareable link.  If
         null, the link is simply the current URL.
    */
    
    initialise (nameForApplicationSpecificTab, { resizablePanels = [], edgeDragging = true } = {}, shareableLinkGenerator = null) // 18-Nov-2026 : Added shareableLinkGenerator.
    {
	/**********************************************************************/
	/* Pick up the application-specific content from the template in the main HTML
	   file.  This is done here, and not when the element is first built, so that
	   the application has the chance to adjust the template first (for instance
	   to generate one tab per map).  Anything which wants to find the contents
	   must therefore wait until this has been called.  In particular, a
	   <j-tabbed-dialog> in the template builds itself from its tabs the moment
	   it is copied into the page, so its tabs must be in the template by now. */

	J_Utils.initialiseTemplates("#j-application-specific-holder-content");



	/**********************************************************************/
	this._initialiseResizers(resizablePanels, edgeDragging);
	this._initialiseInfoBox(shareableLinkGenerator); // 18-Nov-2026: Added shareableLinkGenerator.
	this._initialiseResponsiveLayout(nameForApplicationSpecificTab);
    }


    /**************************************************************************/
    /* IMPORTANT: this deliberately does NOT use a shadow DOM.  The layout has
       to be styled by j_multiPanelLayout.css, and found by id from the rest
       of the code (document.getElementById, J_Utils.initialiseTemplates,
       the responsive layout, the panel resizer ...).

       Page-level CSS and document.getElementById cannot see inside a shadow
       root, so a shadow DOM here leaves the layout unstyled and its ids
       unfindable.  The markup is therefore written into the element's
       ordinary ("light") DOM.

       The element itself is given display: contents (see j_multiPanelLayout.css),
       which means it takes part in no layout of its own, so the divs within it
       behave exactly as though they were written directly in the page. */

    connectedCallback()
    {
	/**********************************************************************/
        /* connectedCallback runs again every time the element is moved in the
           DOM, so make sure we build things only once. */

        if (this._j_initialised) return;
        this._j_initialised = true;



	/**********************************************************************/
        /* The markup is built immediately (other code expects to find the
	   panels as soon as the page has loaded), but kept invisible until
	   the stylesheet has arrived, to avoid a flash of unstyled content. */

        this.style.visibility = "hidden";
        stylesheetLoaded.then(() => { this.style.visibility = ""; });



	/**********************************************************************/
        this.innerHTML = `
  <div class="j-multi-panel-layout-overall-layout">
    <div class="j-multi-panel-layout-column j-multi-panel-layout-left-column j-multi-panel-layout-left-column-auto-vertical-resizing">

      <div class="j-multi-panel-layout-panel j-multi-panel-layout-panel-indented j-multi-panel-layout-top-panel" id="j-search-box-holder">
	<j-input-box-with-options-table id="j-search-container" j-input-box-with-options-name="j-search-box"></j-input-box-with-options-table>
      </div>

      <div class="j-multi-panel-layout-panel j-multi-panel-layout-panel-indented j-multi-panel-layout-bottom-panel" id="j-scripture-holder" style="border-top:1px solid black">
	<iframe id="j-scripture-iframe" src="https://stepbible.org"></iframe>
      </div>
    </div>

    <div class="j-multi-panel-layout-column j-multi-panel-layout-right-column">
      <div class="j-multi-panel-layout-panel j-multi-panel-layout-panel-indented j-multi-panel-layout-top-panel" id="j-info-box-holder">
	<j-info-box id="info-box"></j-info-box>
      </div>

      <div class="j-multi-panel-layout-panel j-multi-panel-layout-panel-indented j-multi-panel-layout-bottom-panel" id="j-application-specific-holder"></div>
    </div>
  </div>
        `;
    }



    /**************************************************************************/
    /* 18-Nov-2026: Rewrote to accept a link generator. */
    
    _initialiseInfoBox (shareableLinkGenerator)
    {
	let fn = null;

	if (null === shareableLinkGenerator)
	    fn = () => {
		const url = window.location.href;
		navigator.clipboard.writeText(url);
		document.querySelector("#info-box").showCopyConfirmationPopup();
	    }

	else
	    fn = () => {
		const url = shareableLinkGenerator();
		navigator.clipboard.writeText(url);
		document.querySelector("#info-box").showCopyConfirmationPopup();
	    }
		
	document.querySelector("#info-box").setUrlToClipboardCopier(fn);
    }

    
    /**************************************************************************/
    /* Makes the panels named in 'resizablePanels' resizable by the user.  For
       each, the edges which can be dragged are the two which face into the
       page.  See j_multiPanelLayout.js for the details. */

    _initialiseResizers (resizablePanels, edgeDragging)
    {
	this._resizers = [];

	/* While the search box is active its options table must be visible, and
	   usable, even if the user has enlarged another panel over the top of it.
	   So when a search starts the search panel is brought to the front.  When
	   the user next enlarges or moves a panel, that panel is brought to the
	   front instead, so that the most recently used panel is always on top
	   and the resize handles can always be reached. */

	const searchHolder = document.getElementById("j-search-box-holder");
	let zIndexWeGave = null;
	let zIndexBefore = "";
	searchHolder?.addEventListener("j-input-box-with-options-table-search-active-change", event => {
	    if (event.detail.active)
	    {
		if (null === zIndexWeGave) zIndexBefore = searchHolder.style.zIndex;
		zIndexWeGave = String(J_PanelResizer.nextZIndex());
		searchHolder.style.zIndex = zIndexWeGave;
	    }
	    else if (null !== zIndexWeGave)
	    {
		if (searchHolder.style.zIndex === zIndexWeGave) searchHolder.style.zIndex = zIndexBefore;   // Unless it has been brought forward since.
		zIndexWeGave = null;
	    }
	});

	const panels = {
	    search:    { id: "j-search-box-holder",           sides: ["bottom", "right"] },
	    scripture: { id: "j-scripture-holder",            sides: ["top",    "right"] },
	    infoBox:   { id: "j-info-box-holder",             sides: ["bottom", "left"]  },
	    app:       { id: "j-application-specific-holder", sides: ["top",    "left"]  }
	};

	resizablePanels.forEach(name => {
	    const panel = panels[name];
	    if (!panel)
		throw new Error(`J_4PanelLayout: unknown panel '${name}' in resizablePanels (expected ${Object.keys(panels).join(", ")}).`);

	    this._resizers.push(J_PanelResizer.makeResizable({ area: document.getElementById(panel.id), sides: panel.sides, permitExpand: true, permitContract: false, edges: edgeDragging }));
	});
    }


    /**************************************************************************/
    /* On screens narrower than 960 pixels, the four panels become four tabs
       of a single tabbed dialog (see j_responsiveLayout.js).  The switch
       happens automatically as the browser window is resized.

       The list below gives the id of each panel and the label for its tab,
       in tab order.  When we switch to the narrow layout panels can no
       longer be resized, so we put them back to their normal size in case the
       user had resized any. */

    _initialiseResponsiveLayout (nameForApplicationSpecificTab)
    {
	J_ResponsiveLayout.initialise({
	    panels: [ { id: "j-search-box-holder",           label: "Search"    },
		      { id: "j-scripture-holder",            label: "Scripture" },
		      { id: "j-info-box-holder",             label: "Info"      },
		      { id: "j-application-specific-holder", label: nameForApplicationSpecificTab } ],

	    initialPanel: "j-application-specific-holder",

	    onLayoutChange: mode => { if ("narrow" === mode) this._resizers.forEach(resizer => resizer.reset()); }
	});
    }
}
customElements.define("j-4panel-layout", J_4PanelLayout);

